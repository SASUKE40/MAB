#!/usr/bin/env node
/*
 * Regenerates the generated docs from the code and the benchmark output:
 *   docs/ALGORITHMS.md  every setting, family and algorithm (rule, guarantee, defaults, notes)
 *   results/README.md   the top three algorithms per environment, from results/<setting>.json
 *
 *   node scripts/catalog.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const M = require('../src/index.js');

const root = path.join(__dirname, '..');
const cell = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const fmt = (v) => {
  if (v == null || !Number.isFinite(v)) return '—';
  const a = Math.abs(v);
  return a >= 100 ? Math.round(v).toLocaleString('en-US') : a >= 10 ? v.toFixed(1) : a >= 0.01 || v === 0 ? v.toFixed(2) : v.toPrecision(2);
};
const fmtBy = (kind, v) => {
  if (v == null || !Number.isFinite(v)) return '—';
  if (kind === 'pct') return (v * 100).toFixed(Math.abs(v) < 0.1 ? 1 : 0) + '%';
  if (kind === 'int') return Math.round(v).toLocaleString('en-US');
  return fmt(v);
};
const total = M.SETTINGS.reduce((n, s) => n + s.algorithms.length, 0);

// ---------------------------------------------------------------- catalog
const out = [];
out.push('# Algorithm catalog', '');
out.push(`Generated by \`node scripts/catalog.js\` from the code. ${total} algorithms in ${M.SETTINGS.length} settings.`, '');
out.push('Simplified implementations say so in their notes. "Guarantee" is the published regret, sample-complexity or estimation guarantee, in short form.', '');
for (const s of M.SETTINGS) out.push(`- [${s.name}](#${s.name.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) (${s.algorithms.length})`);
out.push('');
for (const s of M.SETTINGS) {
  out.push(`## ${s.name}`, '', s.blurb || '', '');
  out.push(`Environments: ${s.environments.map((e) => `**${cell(e.name)}** (\`${e.id}\`)`).join(', ')}.`, '');
  for (const f of s.families) {
    const list = s.algorithms.filter((a) => a.family === f.id);
    if (!list.length) continue;
    out.push(`### ${f.name}`, '', f.blurb || '', '');
    out.push('| Algorithm | id | Rule | Guarantee | Defaults | Notes |', '|---|---|---|---|---|---|');
    for (const a of list) {
      const d = (a.params || []).map((p) => `${p.label.split(' ')[0]} = ${p.default}`).join(', ');
      out.push(`| ${cell(a.name)} | \`${a.id}\` | ${cell(a.formula)} | ${cell(a.regret)} | ${cell(d)} | ${cell(a.idea)} |`);
    }
    out.push('');
  }
}
fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs', 'ALGORITHMS.md'), out.join('\n'));
console.log(`docs/ALGORITHMS.md: ${total} algorithms`);

// ---------------------------------------------------------------- results
const res = [];
res.push('# Benchmark results', '');
res.push('Generated by `node scripts/catalog.js` from `results/<setting>.json`. Each setting\'s full tables (every algorithm, every column) are in `results/<setting>.md`.', '');
res.push('Reproduce with `node scripts/benchmark.js --setting <id> --md results/<id>.md --json results/<id>.json` (the K-armed arena used `--runs 30`; other settings used their default controls).', '');
for (const s of M.SETTINGS) {
  const file = path.join(root, 'results', `${s.id}.json`);
  if (!fs.existsSync(file)) continue;
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const F = s.final;
  const c = data.config || {};
  const bits = [];
  if (c.K != null && s.controls.K) bits.push(`${s.controls.K.label} = ${c.K}`);
  if (c.T != null && s.controls.T) bits.push(`${s.controls.T.label} = ${c.T}`);
  for (const x of s.controls.extra || []) bits.push(`${x.label} = ${c.extra ? c.extra[x.key] : x.default}`);
  bits.push(`${c.runs} runs`);
  res.push(`## ${s.name}`, '', `${bits.join(', ')}. Ranked by ${F.label.toLowerCase()} (${F.better} is better). Full table: [\`results/${s.id}.md\`](${s.id}.md).`, '');
  res.push('| Environment | 1st | 2nd | 3rd | Last |', '|---|---|---|---|---|');
  for (const e of s.environments) {
    const rows = data.environments[e.id];
    if (!rows || !rows.length) continue;
    const v = (r) => fmtBy(s.columns.find((x) => x.key === F.key)?.fmt, r.summary[F.key]);
    const top = rows.slice(0, 3).map((r) => `${cell(r.name)} ${v(r)}`);
    while (top.length < 3) top.push('');
    const last = rows[rows.length - 1];
    res.push(`| ${cell(e.name)} | ${top.join(' | ')} | ${cell(last.name)} ${v(last)} |`);
  }
  res.push('');
}
fs.writeFileSync(path.join(root, 'results', 'README.md'), res.join('\n'));
console.log('results/README.md written');
